CREATE TABLE user_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_user_id BIGINT NOT NULL REFERENCES provider_users(id),
    snapshot_id BIGINT NOT NULL REFERENCES user_snapshots(id),
    raw_payload_id BIGINT NOT NULL REFERENCES raw_payloads(id),
    fetch_log_id BIGINT REFERENCES fetch_logs(id),
    observation_key TEXT NOT NULL UNIQUE,
    captured_at BIGINT NOT NULL,
    endpoint_type TEXT NOT NULL
);
CREATE INDEX idx_user_observations_history ON user_observations(provider_user_id, captured_at DESC, id DESC);
CREATE INDEX idx_user_observations_snapshot ON user_observations(snapshot_id);
CREATE INDEX idx_user_observations_raw_account ON user_observations(raw_payload_id, provider_user_id, captured_at);
INSERT INTO user_observations(provider_user_id, snapshot_id, raw_payload_id,
                             fetch_log_id, observation_key, captured_at, endpoint_type)
SELECT DISTINCT ON(f.id) s.provider_user_id, s.id, f.raw_payload_id, f.id,
       'fetch:' || f.id, f.attempted_at, f.endpoint_type
FROM fetch_logs f
JOIN user_snapshots s ON s.raw_payload_id = f.raw_payload_id
  OR EXISTS(SELECT 1 FROM source_records r WHERE r.entity_type = 'user_snapshot'
            AND r.entity_id = s.id AND r.raw_payload_id = f.raw_payload_id)
WHERE f.status_code IN (200,304)
ORDER BY f.id, s.id DESC;
INSERT INTO user_observations(provider_user_id, snapshot_id, raw_payload_id,
                             observation_key, captured_at, endpoint_type)
SELECT DISTINCT ON(s.raw_payload_id) s.provider_user_id, s.id, s.raw_payload_id,
       'raw:' || s.raw_payload_id, r.fetched_at, r.endpoint_type
FROM user_snapshots s JOIN raw_payloads r ON r.id = s.raw_payload_id
WHERE NOT EXISTS(SELECT 1 FROM fetch_logs f WHERE f.raw_payload_id = s.raw_payload_id AND f.status_code IN (200,304))
ORDER BY s.raw_payload_id, s.id DESC;

