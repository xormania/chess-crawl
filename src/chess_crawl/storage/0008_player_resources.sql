CREATE TABLE user_resource_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_user_id BIGINT NOT NULL REFERENCES provider_users(id),
    owner_scope TEXT NOT NULL DEFAULT 'public',
    resource_key TEXT NOT NULL,
    parameters JSONB NOT NULL DEFAULT '{}',
    parameters_hash TEXT NOT NULL,
    content_hash TEXT NOT NULL,
    native_data JSONB NOT NULL,
    coverage_status TEXT NOT NULL CHECK(coverage_status IN ('observed', 'empty', 'partial', 'unknown')),
    coverage_note TEXT,
    parser_version TEXT NOT NULL,
    UNIQUE(provider_user_id, owner_scope, resource_key, parameters_hash, content_hash)
);
CREATE INDEX idx_user_resource_lookup ON user_resource_snapshots(provider_user_id, owner_scope, resource_key, parameters_hash);
CREATE TABLE user_resource_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL REFERENCES user_resource_snapshots(id),
    raw_payload_id BIGINT NOT NULL REFERENCES raw_payloads(id),
    fetch_log_id BIGINT REFERENCES fetch_logs(id),
    observation_key TEXT NOT NULL UNIQUE,
    captured_at BIGINT NOT NULL
);
CREATE INDEX idx_user_resource_observation_history ON user_resource_observations(snapshot_id, captured_at DESC, id DESC);
CREATE INDEX idx_user_resource_observation_raw ON user_resource_observations(raw_payload_id, snapshot_id, captured_at);

